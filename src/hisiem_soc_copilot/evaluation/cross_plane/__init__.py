"""XP-01 — Cross-Plane Evaluation Pack v1 (Stage E).

A **sibling scenario family inside the existing Evaluation Plane**. It is not a
second evaluation framework, not a second oracle, and not a production path:

```text
existing Evaluation Plane
├── GP-01            sealed grounded-investigation correctness family (untouched)
├── KB-GOLDEN-V1     existing knowledge retrieval-quality family (untouched)
└── XP-01            cross-plane contract / authority / security / reliability gates
```

What E1 establishes here:

* ``contracts``  — pack identity, gate families, execution profiles, measurement
  source categories, the immutable scenario spec, the immutable gate result, and the
  only verdict function (non-compensating).
* ``catalog``    — the audited 29-scenario XP-01 v1 catalog and its validator.
* ``gates``      — the 13 frozen hard gates, their stable reason codes, the machine
  fact vocabulary, typed measurement variants, and pure evaluators.
* ``artifacts``  — the bounded, versioned, secret-scanned gate-results payload
  (pure build/validate; the atomic write lives in the sanctioned harness adapter).

XP-01 does not execute scenarios. Collecting runtime measurements and running the
scenario matrix is E2-E6. Nothing in this package may be imported by a production
layer; ``tests/architecture/test_evaluation_boundary.py`` and
``tests/architecture/test_knowledge_boundary.py`` enforce that.
"""

